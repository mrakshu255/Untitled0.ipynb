def check_answer(q, raw):
    """Returns (status, message). status: 'ok', 'wrong', or 'invalid'."""
    raw = raw.strip()
    if raw == "":
        return "invalid", "Kuch likho pehle."

    if q["type"] == "mcq":
        letters = "ABCD"
        if raw.upper() in list(letters):
            chosen = q["options"][letters.index(raw.upper())]
        else:
            chosen = raw
        return ("ok", "") if chosen.strip().lower() == str(q["correctAnswer"]).strip().lower() else ("wrong", "")

    if q["type"] == "true_false":
        low = raw.lower()
        if low in ("true", "t", "yes", "y"):
            val = True
        elif low in ("false", "f", "no", "n"):
            val = False
        else:
            return "invalid", "Sirf True ya False likho."
        return ("ok", "") if val == q["correctAnswer"] else ("wrong", "")

    if q["type"] == "numerical":
        try:
            val = float(raw)
        except ValueError:
            return "invalid", "Sirf number likho (units mat likho)."
        return ("ok", "") if math.isclose(val, float(q["correctAnswer"]), rel_tol=1e-3, abs_tol=1e-9) else ("wrong", "")

    return "invalid", "Unknown question type."

