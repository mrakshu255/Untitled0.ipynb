def build_collection(chunk_list, vecs=None, name="notes"):
    try:
        chroma_client.delete_collection(name)
    except Exception:
        pass
    c = chroma_client.create_collection(name, metadata={"hnsw:space": "cosine"})
    c.add(
        ids=[str(i) for i in range(len(chunk_list))],
        documents=chunk_list,
        embeddings=vecs if vecs is not None else embed(chunk_list),
    )
    return c

